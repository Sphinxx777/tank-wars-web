#!/usr/bin/env python3
"""Capture original degree conversion/trig and laser geometry with Unicorn.

Original binaries are local-only; fixture values are generated by executing
resident routines dbd:d9, 12ce:12ee, and 12ce:1301 without arithmetic shims.
"""

import struct, math, json
from pathlib import Path
from unicorn import *
from unicorn.x86_const import *

exe = Path("research/original/BOMB.EXE").read_bytes()
ovr = Path("research/original/BOMB.OVR").read_bytes()


def real(v):
    if not v:
        return bytes(6)
    f, e = math.frexp(abs(v))
    return bytes([e + 128]) + (round((f * 2 - 1) * 2**39) | ((v < 0) << 39)).to_bytes(
        5, "little"
    )


def decode(v):
    e = v[0]
    m = int.from_bytes(v[1:], "little")
    return (
        0
        if not e
        else (-1 if m >> 39 else 1)
        * (1 + (m & ((1 << 39) - 1)) / 2**39)
        * 2 ** (e - 129)
    )


def setup():
    u = Uc(UC_ARCH_X86, UC_MODE_16)
    u.mem_map(0, 0x200000)
    u.mem_write(0, exe[0x16A0:])
    u.mem_write(0x60000, exe[0x163F0:])
    u.mem_write(0x20000, ovr[0x10000:])
    for r, n in [
        (UC_X86_REG_CS, 0x2000),
        (UC_X86_REG_DS, 0x6000),
        (UC_X86_REG_SS, 0x7000),
        (UC_X86_REG_SP, 0xF000),
        (UC_X86_REG_BP, 0xF800),
    ]:
        u.reg_write(r, n)
    return u


def invoke(u, cs, ip, regs=None, arg=None):
    u.reg_write(UC_X86_REG_CS, cs)
    u.reg_write(UC_X86_REG_SP, 0xF000)
    u.mem_write(0x7F000, struct.pack("<HH", 0, 0x8000) + (arg or b""))
    if regs:
        for r, n in zip(
            [UC_X86_REG_AX, UC_X86_REG_BX, UC_X86_REG_DX], struct.unpack("<HHH", regs)
        ):
            u.reg_write(r, n)
    u.emu_start(cs * 16 + ip, 0x80000, count=100000)
    return struct.pack(
        "<HHH", *[u.reg_read(r) for r in [UC_X86_REG_AX, UC_X86_REG_BX, UC_X86_REG_DX]]
    )


trig = []
u = setup()
for angle in range(181):
    rad = invoke(u, 0xDBD, 0xD9, arg=real(angle))
    c = decode(invoke(u, 0x12CE, 0x12EE, regs=rad))
    s = decode(invoke(u, 0x12CE, 0x1301, regs=rad))
    trig.append({"angle": angle, "cos": c, "sin": s})
Path("tests/fixtures/runtime-trig-oracle.json").write_text(
    json.dumps(trig, indent=2) + "\n"
)
for angle in [0, 30, 45, 90, 150, 180]:
    u = setup()

    def word(a, v):
        u.mem_write(a, struct.pack("<H", v & 65535))

    word(0x7F806, 1)
    word(0x6403D + 0x74, 50)
    word(0x6403F + 0x74, 100)
    word(0x6404B + 0x74, angle if angle <= 90 else 180 - angle)
    word(0x6404D + 0x74, 1 if angle <= 90 else -1)
    word(0x7F7F8, angle)
    word(0x7F7F6, 1000)
    u.emu_start(0x2470E, 0x2481C, count=100000)
    initial = [
        decode(u.mem_read(0x60000 + a, 6)) for a in [0x4796, 0x479C, 0x47A2, 0x47A8]
    ]
    u.emu_start(0x248C0, 0x24912, count=100000)
    first = [decode(u.mem_read(0x60000 + a, 6)) for a in [0x4796, 0x479C]]
    print(angle, "initial", initial, "first", first, "trig", trig[angle])
